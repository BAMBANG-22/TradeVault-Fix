export const KNOWN_DEMO_TRADE_IDS = new Set(
  DEMO_TRADES.map((t) => t.id.trim().toLowerCase())
);

/**
 * Strictly determines whether a trade record is a built-in DEMO trade.
 * Never matches real user trades even if a user creates custom IDs outside DEMO_TRADES.
 */
export function isDemoTrade(
  trade: Pick<Trade, 'id' | 'isDemo'> | null | undefined
): boolean {
  if (!trade) return false;
  if (trade.isDemo === true) return true;
  const cleanId = String(trade.id || '').trim().toLowerCase();
  return KNOWN_DEMO_TRADE_IDS.has(cleanId);
}

